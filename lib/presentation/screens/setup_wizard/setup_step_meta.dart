/// بندٌ في قائمة التحقّق التي تعرضها الخطوة.
class SetupCheck {
  const SetupCheck(this.label, {this.required = true});

  final String label;

  /// `false` ⇒ اختياريٌّ — يُعرَض بعلامةٍ أخفتَ ولا يمنع المتابعة.
  final bool required;
}

/// ملاحظةٌ ملوّنةٌ أسفلَ لوحة الشرح.
class SetupNote {
  const SetupNote({
    required this.title,
    required this.body,
    required this.icon,
    required this.tone,
  });

  final String title;
  final String body;
  final IconData icon;

  /// لونُ الملاحظة كما في التصميم — تحذيرٌ أو معلومةٌ أو خطر.
  final Color tone;
}

/// وصفُ خطوةٍ واحدةٍ في المعالج.
