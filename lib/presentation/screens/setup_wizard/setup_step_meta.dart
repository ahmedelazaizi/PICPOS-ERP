  final String title;

  /// سطرُ الوصف تحته.
  final String sub;

  /// «لماذا هذه الخطوة» — تشرح الأثرَ لا الإجراء.
  final String why;

  final List<SetupCheck> checks;
  final SetupNote note;
}

