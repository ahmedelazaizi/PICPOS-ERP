  ///
  /// ⚠️ **لا تعدّله**: هو مفتاحُ الربط بين السجلّ وجسمِ الخطوة، وتبديلُه
  /// يعرض عنوانَ خطوةٍ فوقَ جسمِ أخرى بلا أن ينهار شيء.
  final int index;

  /// العنوانُ في العمود الجانبيّ.
  final String label;

  /// السطرُ الخافتُ تحته في العمود.
  final String hint;

