// عدّادُ إعدادات القسم — «١٤ إعداداً» بجانب اسمِ القسم في التصميم.
//
// ═══ ⚠️ لماذا يُمشى على الشجرة ولا يُكتَب رقمٌ ═══
//
// أرقامُ التصميم أرقامُ **نموذجٍ** لا تقابل شيئاً في التطبيق. قِيس ذلك
// 2026-08-25: التصميمُ يكتب «١١» بجانب «البيع السريع»، وحوارُ ذلك القسم
// وحدَه فيه **٦٣ مفتاحَ إعداد**، والقسمُ يعرض **ثلاثةَ بلوكات**. فلا نسبةَ
// بين الرقمَين ولا اشتقاق.
//
// ونسخُ رقم التصميم كان سيعطي رقماً يكذب — وهو أسوأُ من لا رقم، لأنّ صاحبَه
// يبني عليه. وكتابةُ رقمٍ بيدِ المطوّر تنحرف عند أوّل إعدادٍ يُضاف أو يُحذَف
// بلا أن ينبّه أحد.
//
// فالعدُّ هنا **مقيسٌ من الشجرة التي تُبنى فعلاً**: يمشي على ما يعيده
// `children()` للقسم ويعدّ ما يراه المستخدم. لا يمكنه أن يكذب لأنّه لا يحمل
// معرفةً خاصّةً به — إن أُضيف صفٌّ ارتفع، وإن حُذف نزل.
//
// ═══ ما الذي يُعَدُّ «إعداداً واحداً» ═══
//
// قرارُ المالك 2026-08-25: **عددُ ما يُعرَض** لا عددُ المفاتيح تحته.
//
//   • كلُّ صفٍّ ظاهر (`SettingsValueRow` · `SettingsSwitchRow` ·
//     `SettingsDangerRow`) = ١
//   • كلُّ اختيارٍ (`SettingsChoiceBlock`) = ١ — إعدادٌ واحدٌ بخياراتٍ عدّة
//     لا إعداداتٌ بعددها
//   • كلُّ مربّعٍ في `SettingsTilesBlock` = ١
//   • وبلوكٌ لا يُرى داخلَه شيءٌ معروف = ١ — لأنّه شيءٌ واحدٌ يُفتَح ويُغيَّر
//     (‏بطاقةُ «إعدادات البيع السريع» تفتح حواراً؛ هي إدخالٌ واحدٌ للمستخدم).
//     وبغير هذا البند كان القسمُ الذي كلُّ بلوكاته بطاقاتٌ خاصّةٌ يقرأ **صفراً**
//     — وصفرٌ في قسمٍ مليءٍ بالإعدادات كذبٌ من نوعٍ آخر.
library;

import 'package:flutter/widgets.dart';

import 'settings_blocks.dart';

/// يعدّ الإعداداتِ الظاهرةَ في [children] — ما يعيده `_SettingsSection`.
int countVisibleSettings(List<Widget> children) {
  var total = 0;
  for (final w in children) {
    total += _count(w);
  }
  return total;
}

/// كـ[countVisibleSettings] لكن يعيد `null` بدل الصفر.
///
/// ⚠️ **الصفرُ لا يُعرَض شارةً.** قسمٌ يبني بطاقاتٍ خاصّةً لا يعرفها العدّاد
/// (‏«عن البرنامج»: الإصدارُ والترخيصُ ونسخُ السجلّ) يعود بصفر — و«٠ إعداد»
/// بجانبه كذبٌ كالرقم المخترَع. فالصمتُ أصدقُ من صفرٍ لا يعني شيئاً.
int? countVisibleSettingsOrNull(List<Widget> children) {
  final n = countVisibleSettings(children);
  return n > 0 ? n : null;
}

/// يعدّ ودجتاً واحداً وما تحته.
///
/// يعود بـ`0` للودجت الذي لا يحمل إعداداً ولا يُعرَف داخلُه (‏فاصلٌ أو
/// `SizedBox`)؛ ويعود بـ`1` للورقة المعروفة. والبلوكُ يُعالَج خاصّةً:
/// يحاول أن يعدّ ما بداخله، فإن لم يجد شيئاً عُدَّ نفسُه واحداً.
int _count(Widget w) {
  // ─── أوراقٌ معروفة ───────────────────────────────────────────────────
  if (w is SettingsValueRow) return 1;
  if (w is SettingsSwitchRow) return 1;
  if (w is SettingsDangerRow) return 1;

  // اختيارٌ واحدٌ بخياراتٍ عدّة — إعدادٌ واحدٌ لا بعددِ خياراته.
  // (‏`SettingsChoiceBlock<T>` مولَّدٌ، فيُطابَق باسم النوع لا بـ`is`.)
  if (w.runtimeType.toString().startsWith('SettingsChoiceBlock')) return 1;

  // ─── حاوياتٌ معروفة ──────────────────────────────────────────────────
  if (w is SettingsTilesBlock) return w.tiles.length;

  if (w is SettingsBlockGrid) {
    var n = 0;
    for (final b in w.blocks) {
      n += _count(b.child);
    }
    return n;
  }

  if (w is SettingsRowsBody) {
    var n = 0;
    for (final c in w.children) {
      n += _count(c);
    }
    return n;
  }

  if (w is SettingsBlock) {
    final inner = _count(w.child);
    // بلوكٌ لا يُرى داخلَه شيءٌ معروف (‏بطاقةٌ خاصّةٌ تفتح حواراً) = إدخالٌ
    // واحدٌ للمستخدم. انظر رأسَ الملفّ.
    return inner > 0 ? inner : 1;
  }

  // ─── حاوياتُ Flutter العامّة ─────────────────────────────────────────
  //
  // تُمشى لأنّ الأقسامَ تركّب `Column`/`Padding` حولَ بلوكاتها أحياناً.
  // وما عداها يعود صفراً: العدُّ يقيس المعروفَ ولا يخمّن.
  if (w is Column) {
    var n = 0;
    for (final c in w.children) {
      n += _count(c);
    }
    return n;
  }
  if (w is Padding) return w.child == null ? 0 : _count(w.child!);

  return 0;
}
