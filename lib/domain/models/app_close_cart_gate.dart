// بوّابةُ إغلاق البرنامج وسلّةُ البيع — طلبُ مالكٍ 2026-08-17.
//
// ── البلاغ ────────────────────────────────────────────────────────────────
// «عند وجود اصناف بالسلة وعمل اغلاق، السيستم يقدر يعمل اغلاق وهذا خطأ — لا
// بد ان يطلب حذف الاصناف من السلة قبل الاغلاق.»
// المقيسُ: `app_main_screen.dart#onWindowClose` يغلق الحواراتِ ثم يعالج وضعَ
// السيرفر ثم يؤكّد الإغلاقَ — ولا فحصَ للسلّة في أيّ موضع. وكذلك مخارجُ
// إغلاقٍ أخرى (`app_shell.dart` و`login_screen.dart`) تنادي
// `platform.exitApp()`/`exit(0)` مباشرةً بلا مرورٍ بـ`onWindowClose` إطلاقاً.
//
// ── لماذا دالّةٌ خالصة هنا ────────────────────────────────────────────────
// `onWindowClose` يحتاج `windowManager` (لا يُبنى في اختبارات الوحدة)،
// والمخارجُ الأخرى تحتاج `BuildContext`/`Ref`. عزلُ *قرارِ* المنع وحده —
// بلا أيٍّ من هذه — يجعله قابلاً للاختبار مباشرةً، ونقاطُ الاستدعاء تبقى
// مسؤولةً فقط عن القراءة والعرض.
//
// ── قرارُ مالكٍ: منعٌ لا تخيير ────────────────────────────────────────────
// لا زرّ «أغلق على أي حال» — طلبُ المالك «لا بد أن يطلب حذف الأصناف قبل
// الإغلاق». والمنعُ لا يمسح السلّةَ تلقائياً (يُتلف عملَ الكاشير)؛ هو يحسمها
// بنفسه (بيعاً أو تعليقاً أو مسحاً يدوياً) ثم يعيد الإغلاق.

/// هل يجب منعُ إغلاق/إنهاء البرنامج بسبب أصنافٍ في سلة البيع؟
///
/// [saleCartItemCount] عددُ أصناف **سلة البيع الحقيقية** —
/// `cartControllerProvider` state — وليس أيّ حالةٍ أخرى. تحذيرٌ مقيس: في
/// وضع المرتجع، الزرّ المكافئ في `picpos_payment_panel.dart` يحسب فراغَه من
/// `posReturnModeProvider` (سلّةُ المرتجع منفصلةٌ عمداً ولا تكتب على
/// `cartController`) — تلك البوابةُ *غير* هذه، وهذه البوابةُ تتجاهلها كلياً
/// وتنظر إلى سلّة البيع وحدها.
bool shouldBlockAppCloseForCart(int saleCartItemCount) =>
    saleCartItemCount > 0;

/// هل يُمنع التنقّلُ عن شاشة البيع إلى شاشةٍ أخرى؟ (قرارُ مالكٍ 2026-10-30)
///
/// يُمنع فقط حين: شريطُ التابات مخفيّ ([tabsBarVisible] = false) **و**
/// التابُ النشطُ هو البيع ([activeIsPos]) **و**
/// السلّةُ غير فارغة. مع الشريط الظاهر يبقى السلوكُ كما هو (الحارسُ أُزيل
/// عمداً هناك لأنّ التابَ يُبقي السلّةَ حيّة والشريطُ يذكّر الكاشير بها).
/// منعٌ لا تخيير: لا خيارَ «متابعة».
bool shouldBlockNavigationAwayFromPos({
  required bool tabsBarVisible,
  required bool activeIsPos,
  required int saleCartItemCount,
}) => !tabsBarVisible && activeIsPos && saleCartItemCount > 0;

/// هل يُمنع تسجيلُ الخروج بسبب أصنافٍ في سلة البيع؟ — بصرف النظر عن
/// ظهور شريط التابات. (كان الخروج يفرّغ السلّةَ بصمت.)
bool shouldBlockLogoutForCart(int saleCartItemCount) => saleCartItemCount > 0;
