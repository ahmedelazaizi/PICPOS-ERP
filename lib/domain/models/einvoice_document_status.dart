/// ترجمةُ حكم بوّابة الفوترة إلى الحالة المخزَّنة — دالّةٌ خالصة.
///
/// البوّابةُ تردّ نصّاً حرّاً بحروفٍ تختلف (`Valid` · `valid` · `Accepted`)،
/// والمخزَّنُ عندنا اصطلاحٌ ثابت: `valid` · `invalid` · `rejected` ·
/// `cancelled`.
library;

/// الحالاتُ النهائيّةُ التي نخزّنها — وما عداها ليس حكماً.
const _terminal = <String, String>{
  'valid': 'valid',
  'accepted': 'valid',
  'invalid': 'invalid',
  'rejected': 'rejected',
  'cancelled': 'cancelled',
  'canceled': 'cancelled',
};

/// يُرجع الحالةَ المخزَّنة، أو `null` حين **لا حكمَ بعد**.
///
/// ⚠️ **و`null` تشمل المجهول عمداً**: حالةٌ لا نعرفها — صيغةٌ جديدةٌ من
/// البوّابة أو ردٌّ مشوّه — تُترك بلا تغيير فيُعاد استطلاعُها. وترجمتُها إلى
/// حكمٍ نهائيٍّ تُجمّد المستندَ عند حالةٍ خاطئة: إمّا رمزٌ ضريبيٌّ يُطبع على
/// مستندٍ لم يُعتمد، وإمّا مستندٌ معتمَدٌ يُوسَم مرفوضاً فلا يُطبع رمزُه أبداً.
String? canonicalEInvoiceStatus(String raw) => _terminal[raw.trim().toLowerCase()];
