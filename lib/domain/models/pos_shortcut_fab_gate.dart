// زرٌّ عائمٌ دائمٌ للعودة إلى «البيع السريع» — طلبُ مالكٍ 2026-08-17.
//
// ── البلاغ ────────────────────────────────────────────────────────────────
// «عند التعامل بحساب الكاشير… يكون فى زر جانبي للتوجيه الى نقطة البيع
// مباشرة بدلا من الاختيار من القائمة: المبيعات ثم بيع سريع — امكانية
// الرجوع الى نقطة البيع.»
//
// ── قرارُ المالك في الموضع (سُئل صراحةً واختار) ───────────────────────────
// زرٌّ عائمٌ دائمٌ — صغيرٌ ثابتٌ في حافة الشاشة، يظهر في **كلّ** الشاشات ما
// دام المستخدمُ يملك صلاحيةَ نقطة البيع، فيعود من التقارير أو الأصناف
// بضغطةٍ واحدة، **ويعمل في وضع الكاشير حيث تختفي القائمة** (`AppShell`
// يُخفي الشريط الجانبي بالكامل للكاشير غير المرفوع — `_isHidden`).
//
// ── لماذا دالّةٌ خالصة هنا ────────────────────────────────────────────────
// `AppShell` ودجتٌ ضخمةٌ (Riverpod + Scaffold كامل)؛ عزلُ *قرارِ* الظهور
// وحده يجعله قابلاً للاختبار مباشرةً بلا شجرة ودجت هشّة. نقطةُ الاستدعاء
// (`app_shell.dart`) مسؤولةٌ فقط عن قراءة الصلاحية والشاشة الحالية وتمريرها.

/// هل يجب إظهارُ الزرّ العائم لشاشة «البيع السريع»؟
///
/// [hasPosAccess] صلاحية `pos_access` — نفسُ الكود الذي يحرس عنصر القائمة
/// «البيع السريع» في `kAllNavItemDefs` (`data/providers/auth_providers.dart`)،
/// محسوبةً بنفس منطق `hasPermissionWithAdminBypass` المستخدَم في بقية أزرار
/// الواجهة (`presentation/widgets/permission_guard.dart`). من لا يملكها لا
/// يرى الزرَّ إطلاقاً — لا اختصارَ لشاشةٍ ممنوعة.
///
/// [isOnPosScreen] الشاشةُ الحاليةُ هي شاشةُ البيع نفسها. زرُّ عودةٍ إلى ما
/// أنت فيه أصلاً ضجيجٌ لا فائدة — فلا يظهر هناك.
bool shouldShowPosShortcutFab({
  required bool hasPosAccess,
  required bool isOnPosScreen,
}) {
  if (!hasPosAccess) return false;
  if (isOnPosScreen) return false;
  return true;
}
