/// تاريخُ الاستحقاق، أو `null` حين **لا مهلةَ متّفقاً عليها**.
///
/// ⚠️ **و`null` ليست «اليوم»**: عمودُ `due_date` يقرأ فراغَه على أنّه
/// «بلا مهلة» فيرجع إلى `invoice_date` في حساب التقادم
/// (`COALESCE(due_date, invoice_date)`). فكتابةُ تاريخ الفاتورة نفسِه هنا
/// كانت ستُنتج نفسَ الرقم، لكنّها تمحو التفرقةَ بين «فاتورةٍ بلا أجل»
/// و«فاتورةٍ أجلُها صفر» على كلّ صفٍّ قديم.
///
/// وصفرٌ أو سالبٌ ⇒ `null`: مهلةٌ غيرُ مضبوطةٍ لا مهلةٌ فوريّة.
DateTime? resolveDueDateFromTerms({
  required DateTime invoiceDate,
  required int? paymentTermsDays,
}) {
  final days = paymentTermsDays ?? 0;
  if (days <= 0) return null;
  return invoiceDate.add(Duration(days: days));
}
