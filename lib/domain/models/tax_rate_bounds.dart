/// حدودُ نسبةِ الضريبة — الجملةُ الواحدةُ التي تنطق بها الحُرّاسُ الثلاثة.
///
/// ضريبةٌ «مفعَّلةٌ» بنسبةِ صفرٍ حالةٌ تكذب، وv156 جعلها مستحيلةَ التمثيل بقيدٍ
/// في الجدول. لكنّ `tax_rate > 0` تقبل `0.0000001`: الزرُّ «مفعَّل»، والقيدُ
/// راضٍ، والمحصَّلُ صفرٌ بعد التقريب — **الكذبةُ نفسُها** بصورةٍ أدقَّ تمرّ من
/// تحت القيد. وهذه الحدودُ تسدّها.
///
/// **المجموعةُ المسموحة `{0} ∪ [1٪, 100٪]`** — والصفرُ فيها عن قصد: هو تعبيرُ
/// «هذا المحلُّ بلا ضريبة»، ومعالجُ التهيئة يكتبه صراحةً عند إطفاء الضريبة.
/// المرفوضةُ هي الفجوةُ بينهما وحدَها: نسبةٌ تُدَّعى ولا تُحصَّل.
///
/// و[minPercent] هي ١٪ لا غيرها لأنها تطابق مدى `assert` القائمَ في
/// `TableOrderTotals` — فيتّسق الحارسان بدل أن يتناقضا. ولا ضريبةَ مبيعاتٍ
/// إجماليّةً في الدنيا دون ١٪ ولا فوق ١٠٠٪.
///
/// ثلاثةُ مواضعَ تقرأ من هنا:
/// - شاشةُ الإعدادات — ترفض المدخلَ عند المصدر (`pos_default_tax_rate`).
/// - `TableSessionService.setOrderTax` — يرفض تفعيلَ زرٍّ بلا نسبةٍ حقيقيّة.
/// - `TableOrderTotals._requirePercent` — حارسُ الوحدات في التطوير.
///
/// ورابعٌ لا يستطيع الاستيرادَ فيُربَط باختبار: قيدُ `CHECK` في
/// `TableOrders.customConstraints` — الملفُّ `part` بلا استيرادات، فالرقمُ
/// حرفيٌّ هناك ويؤكّد `table_tax_check_constraint_test.dart` تطابقَه مع
/// [minRate].
class TaxRateBounds {
  TaxRateBounds._();

  /// الحدُّ الأدنى **كسريّاً** (0.01 = ١٪) — مرآةُ `pos_default_tax_rate`
  /// و`TableOrders.taxRate`.
  ///
  /// وهو بتُّه بتُّ `1.0 / 100` الذي تحفظه الشاشة، فلا تُنتج الشاشةُ قيمةً
  /// أجازها مُتحقِّقُها ثم يرفضها القيد.
  static const double minRate = 0.01;

  /// الحدُّ الأدنى **مئويّاً** (1.0 = ١٪) — مرآةُ `TableOrderItems.taxRate`
  /// و`Products.taxRate` وحقلِ الشاشة.
  static const double minPercent = 1.0;

  /// الحدُّ الأعلى مئويّاً. ما فوقه كسريّةٌ قُرئت مئويّةً فضُربت في ١٠٠.
  static const double maxPercent = 100.0;

  /// هل هذه النسبةُ **المئويّةُ** ضمن المسموح؟
  ///
  /// الصفرُ مقبولٌ («لا ضريبة»)، وما بين الصفرِ و[minPercent] مرفوضٌ لأنه
  /// يَعِد بضريبةٍ لا تُحصَّل.
  static bool isValidPercent(double percent) =>
      percent == 0 || (percent >= minPercent && percent <= maxPercent);
}
