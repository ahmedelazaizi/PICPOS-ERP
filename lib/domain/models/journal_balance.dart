// اتّزانُ القيد — **سؤالٌ واحدٌ بجوابٍ واحد.**
//
// ═══ فئةُ العطب ═══
//
// «هل هذا القيدُ متوازن؟» يُجاب في المستودع من مصدرَين لا واحد:
//
//   ‏• **جانبُ الكتابة** يقرأ [FinancialUtils.balanceTolerance] — وهي
//     مُعلَنةٌ صراحةً «‏the ONE allowed debit-vs-credit tolerance» (‏Spec 139)،
//     ويقرؤها كاتبُ القيد ومصنعُه ومُصادِقُ المزامنة.
//   ‏• **وجانبُ العرض والإدخال** يكتبها بيده في خمسة مواضع: شاشةُ اليومية
//     `< 0.005`، وحوارا الإنشاء وحوارُ القوالب وتقريرُ ميزان المراجعة
//     `< 0.01`.
//
// 🔴 **وشاشةُ العرض أشدُّ من المُصادِق.** فقيدٌ يصل بالمزامنة بفرق ٠٫٠٠٧
// يقبله `journal_sync_strategy` ويكتبه، ثمّ تعرضه الشاشةُ **«غير متوازن»** —
// والمستخدمُ لا يملك ما يصلحه به، ولا يوجد في النظام ما يقول أيُّهما محقّ.
//
// ═══ والقرارُ يجعل التناقضَ مرئيّاً ═══
//
// قرارُ المالك 2026-09-18 على تصميم اليومية العامة: «الفرق» **رقماً وشارةَ
// متوازن/غير متوازن معاً**. فالرقمُ المعروضُ والشارةُ يخرجان من حسابٍ واحد
// — وإلّا عُرض «٠٫٠٠٧» بجوار شارةٍ تقول «غير متوازن» بينما كتبه النظامُ
// متوازناً.
//
// ⚠️ **ولا تخترع هذه الوحدةُ سماحيّةً**: تقرأ القائمةَ حرفاً. والتوحيدُ
// **يُرخي** شاشةَ اليومية من ٠٫٠٠٥ إلى ٠٫٠١ — وهو الاتّجاهُ الصحيح، لأنّ
// المحرّكَ يَعُدُّ ما دون ٠٫٠١ بقيّةَ تقريبٍ مشروعةً ويقيّدها في حساب «فروق
// التقريب». فشاشةٌ ترفض ما قبله المحرّكُ تناقضُ دفترَها.

import 'dart:math' as math;

import '../../core/utils/financial_utils.dart';

/// اتّزانُ قيدٍ واحد — يُحسَب من مجموعَي سطوره.
class JournalBalance {
  const JournalBalance({required this.debit, required this.credit});

  /// مجموعُ المدين في سطور القيد.
  final double debit;

  /// مجموعُ الدائن في سطور القيد.
  final double credit;

  /// الفرقُ **بإشارته** — موجبٌ يعني مديناً زائداً.
  ///
  /// ⚠️ **والإشارةُ تُعرَض لا تُبتلَع**: «الفرق ٥٠» لا يقول أيَّ الطرفَين
  /// ناقص، و«٥٠−» يقوله. والقيمةُ المطلقةُ في [magnitude] لمن يريدها.
  double get difference => debit - credit;

  double get magnitude => difference.abs();

  /// الفرقُ **بالوحدات الصغرى** — صحيحٌ لا كسرٌ عائم.
  int get differenceMinorUnits =>
      FinancialUtils.toMinorUnits(debit) - FinancialUtils.toMinorUnits(credit);

  /// هل يتّزن؟ — **بعينِ الحساب الذي يجريه كاتبُ القيد**.
  ///
  /// 🔴 **وبالوحدات الصغرى لا بالكسر العائم.** المقارنةُ
  /// `(debit - credit).abs() < 0.01` تكذب على حدّها بالضبط: فرقُ وحدةٍ صغرى
  /// واحدةٍ يعطي `0.009999999999990905` فيمرّ بالمصادفة لا بالقاعدة —
  /// ويسقط بمصادفةٍ أخرى على أرقامٍ غيرها. و`accounting_dao_writes` يقارن
  /// `residualMinor.abs() <= balanceToleranceMinorUnits` على أعدادٍ صحيحة،
  /// فهذا يطابقه **بالبناء** لا بالتقريب.
  ///
  /// ⚠️ **و`<=` لا `<`**: بقيّةٌ مقدارُها وحدةٌ صغرى واحدةٌ يقيّدها الكاتبُ
  /// في حساب «فروق التقريب» **ويَعُدُّ القيدَ متوازناً**. فعرضٌ يرفضها
  /// يناقض الدفترَ الذي كتبها.
  bool get isBalanced =>
      differenceMinorUnits.abs() <= FinancialUtils.balanceToleranceMinorUnits;

  /// قيدٌ فارغٌ (بلا سطور) **متّزنٌ حسابيّاً وليس صالحاً للترحيل**.
  ///
  /// ⚠️ والتفرقةُ مقصودة: حوارُ الإنشاء يشترط `totalDebit > 0` فوق الاتّزان،
  /// وخلطُ الشرطَين في رايةٍ واحدةٍ كان يجعل «متوازن» تعني شيئَين.
  bool get isEmpty => debit == 0 && credit == 0;

  /// اتّزانٌ **وقابليّةُ ترحيل** معاً — شرطُ حوارات الإنشاء.
  bool get isPostable => isBalanced && debit > 0;

  static JournalBalance of(Iterable<({double debit, double credit})> lines) {
    var d = 0.0;
    var c = 0.0;
    for (final l in lines) {
      d += l.debit;
      c += l.credit;
    }
    return JournalBalance(debit: d, credit: c);
  }

  /// مجموعُ عدّةِ قيودٍ — لشريط إجماليّات الصفحة.
  static JournalBalance sum(Iterable<JournalBalance> parts) {
    var d = 0.0;
    var c = 0.0;
    for (final p in parts) {
      d += p.debit;
      c += p.credit;
    }
    return JournalBalance(debit: d, credit: c);
  }

  /// أقصى فرقٍ في أيّ قيدٍ منفرد — **لا فرقُ المجموع**.
  ///
  /// 🔴 **والتفرقةُ ماليّةٌ لا تجميليّة**: قيدان أحدُهما مدينُه زائدٌ ١٠٠
  /// والآخرُ دائنُه زائدٌ ١٠٠ يعطيان مجموعاً فرقُه **صفر**. فشريطٌ يعرض فرقَ
  /// المجموع يقول «متوازن» وفي الصفحة قيدان مكسوران.
  static double worstOf(Iterable<JournalBalance> parts) {
    var worst = 0.0;
    for (final p in parts) {
      worst = math.max(worst, p.magnitude);
    }
    return worst;
  }
}
