// ═══════════════════════════════════════════════════════════════════════════
// «الرصيد بعد» رصيداً جارياً على النافذة المفلترة — الحسابُ الخالص
// ═══════════════════════════════════════════════════════════════════════════
//
// `safe_transactions.balanceAfter` **لقطةٌ وقتَ الإدراج**:
//   · تحت التصفية (مدىً/خزنة) لا تعني شيئاً — أوّلُ صفٍّ معروضٍ يبدأ من رقمٍ
//     لا علاقةَ له بما فوقه، فالعمودُ يقفز بلا تفسير.
//   · وبعد إلغاء حركةٍ سابقة (حذفٌ ناعم) تبقى لقطاتُ ما بعدها على حالها،
//     فتصير كلُّها خاطئةً **صامتة** — أرقامٌ موجودةٌ ومعقولةٌ وغلط.
//
// البديل: رصيدٌ افتتاحيٌّ للنافذة يُحسب من الحركات السابقة لها، ثم مشيٌ
// تصاعديٌّ فوقه. فالعمودُ يصف النافذةَ المعروضة نفسَها، ويتّسق مع عمود
// المبلغ فوقه سطراً بسطر.

/// صفُّ حركةٍ مختزَلٌ إلى ما يلزم الحساب — بلا اعتمادٍ على drift كي يبقى
/// الحسابُ قابلاً للقياس وحدَه.
class SafeMovementRow {
  final int id;
  final String type;
  final double amount;
  const SafeMovementRow({
    required this.id,
    required this.type,
    required this.amount,
  });
}

/// أثرُ حركةٍ على رصيد الخزنة، موقَّعاً.
///
/// ⚠️ لا قاعدةَ تصريحيةً واحدةً في المشروع تربط النوعَ بالإشارة — كلُّ موضعٍ
/// يمرّر دلتا صريحةً لمسار تعديل الرصيد. فهذه القاعدةُ **مستنبَطةٌ** من
/// المواضع، ولذلك يقيسها اختبارُ ثباتٍ على قاعدةٍ حقيقية: المشيُ فوق كلّ
/// حركات خزنةٍ يجب أن ينتهي عند `safes.balance` نفسِه. أيُّ نوعٍ جديدٍ
/// تُخطئ إشارتُه يُسقط ذلك الاختبار بدل أن ينحرف عمودٌ صامتاً.
///
/// و`memo` صفرٌ لا سالب: صفوفُ المذكّرة مكتوبةٌ عمداً بنوعٍ متمايزٍ «كي
/// تتخطّاها استعلاماتُ التجميع بدل أن تحسبها مرّتين» (‏موثَّقٌ عند مواضع
/// كتابتها في مسار المشتريات والمرتجعات). وكان الجدولُ يعرضها «−المبلغ».
///
/// والمجهولُ يُعامَل صرفاً: الأحوطُ ألّا نضخّم رصيداً بنوعٍ لم نعرفه.
double signedSafeDelta(String transactionType, double amount) {
  switch (transactionType) {
    case 'receipt':
      return amount;
    case 'memo':
      return 0.0;
    default:
      return -amount;
  }
}

/// `{معرّفُ الحركة: الرصيدُ الجاري بعدها}`.
///
/// [rowsNewestFirst] بترتيب الاستعلام كما هو (‏`OrderingTerm.desc` على
/// `createdAt`)، فالمشيُ يبدأ من آخر القائمة صعوداً. تمريرُ الترتيب كما يصل
/// — لا معكوساً في موضع النداء — يمنع خطأً صامتاً لو تغيّر الترتيب لاحقاً:
/// المسؤوليةُ في مكانٍ واحدٍ موثَّق.
Map<int, double> runningBalances({
  required List<SafeMovementRow> rowsNewestFirst,
  required double openingBalance,
}) {
  if (rowsNewestFirst.isEmpty) return const {};
  final out = <int, double>{};
  var running = openingBalance;
  for (var i = rowsNewestFirst.length - 1; i >= 0; i--) {
    final row = rowsNewestFirst[i];
    running += signedSafeDelta(row.type, row.amount);
    out[row.id] = running;
  }
  return out;
}
