// أيُّ الطرقِ تمسّ خزنةً بنكيّةً وأيُّها تمسّ الدرج
// ═══════════════════════════════════════════════════════════════════════════
//
// المواصفة: docs/superpowers/specs/2026-08-18-sales-return-cash-shift-rule-design.md
//
// عطبٌ من جنسِ ما عالجه رأسُ هذا الملفّ، في بُعدٍ آخر: كانت القائمةُ مكرَّرةً
// بصيغتَين متفاوتتَين — مسارُ البيع يعرف ثمانياً، وتسعةُ مواضعَ أخرى تعرف
// ثلاثاً فقط (`transfer, card, bank`).
//
// فبيعةٌ بـ`visa` تدخل الخزنةَ **البنكيّة** (القائمة الواسعة)، ومرتجعُها يخرج
// نقداً من **الدرج** (القائمة الضيّقة). والنتيجةُ عطبٌ مزدوجٌ لا يتقاصّ:
//   • الدرجُ ينقص بلا سببٍ ⇒ عجزٌ عند الإقفال في ذمّة الكاشير.
//   • والخزنةُ البنكيّةُ تبقى منتفخةً بمبلغٍ رُدَّ فعلاً ⇒ رصيدٌ بنكيٌّ وهميّ.
// أحدهما نقصٌ في درجٍ والآخرُ زيادةٌ في بنك، فلا يلغي أحدُهما الآخرَ أبداً.

/// طرقُ الدفع التي تُسوَّى **إلكترونيّاً** فتمسّ خزنةً بنكيّةً لا درجاً.
///
/// لا تدخل `expectedCash` عند إقفال الورديّة، ولا تستلزم ورديّةً مفتوحة
/// (‏ح‑١ في المواصفة) — لأنّ لا درجَ يتحرّك بها.
///
/// ⚠️ `click` **ليست** منها: لها نوعُ خزنةٍ مستقلٌّ (`safeType: 'click'`)
/// يعامله مسارُ البيع على حدة، فإدراجُها هنا كان سيوجّه تحصيلَها إلى الخزنة
/// البنكيّة بدل خزنة كليك.
const Set<String> kBankPaymentMethods = {
  'bank',
  'card',
  'transfer',
  'visa',
  'mastercard',
  'amex',
  'mada',
  'stcpay',
};

/// هل تمسّ [paymentMethod] خزنةً بنكيّةً بدل الدرج؟
bool isBankPaymentMethod(String? paymentMethod) =>
    paymentMethod != null && kBankPaymentMethods.contains(paymentMethod);
