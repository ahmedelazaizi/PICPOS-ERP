final _seededFiscalYearName = RegExp(r'^السنة المالية ([0-9٠-٩]+)$');

/// Localizes an exact system-seeded display name without changing stored data.
String trData(String? stored) {
  final value = stored ?? '';
  if (I18nCatalog.activeLocale.languageCode != 'en') return value;
  if (_seededDefaultNames.contains(value)) return tr(value);

  final fiscalYear = _seededFiscalYearName.firstMatch(value);
  if (fiscalYear != null) {
    return tr('السنة المالية {year}', {'year': fiscalYear.group(1)!});
  }
  return value;
}
