// ═══════════════════════════════════════════════════════════════════════════
// BRAND — الهوية البصرية، مصدر واحد للحقيقة
// ═══════════════════════════════════════════════════════════════════════════
//
// المشروع بيطلّع أكتر من منتج مستقل من نفس الكود (UralCash, PicPos). الفرق
// بينهم هوية بحتة: الاسم، اللوجو، الألوان، اسم الملف التنفيذي، ملف البيانات.
// المحرك (محاسبة، مخزون، خزائن، مزامنة) مشترك بالكامل.
//
// ── ليه compile-time وليس runtime؟ ──────────────────────────────────────────
// حاجات زي اسم الـ `.exe` وأيقونة الويندوز وملف التنصيب بتتحدد وقت البناء
// أصلاً — مستحيل تتغير من إعدادات داخل البرنامج. فالعلامة لازم تكون
// `--dart-define=APP_BRAND=<id>`.
//
// ── ليه كل حاجة هنا `const`؟ ────────────────────────────────────────────────
// `String.fromEnvironment` هي نفسها `const`, فالتفريع بينفّذ وقت الترجمة.
// ده مش تفصيلة أسلوبية: `AppColors` فيها ٤٥٣٧ استخدام عبر ٣٥٥ ملف، منهم ~٤٩١
// جوّه سياق `const` (زي `const Icon(..., color: AppColors.primary)`). لو أي
// قيمة هوية بقت تُقرأ وقت التشغيل، كل المواضع دي بتتحول لأخطاء ترجمة.
// الشرط ده لازم يفضل محفوظ في أي إضافة هنا: **متضفش حاجة مش const**.
//
// ── تحذير: الاسم مستخدم كملح تشفير ─────────────────────────────────────────
// `api_auth_middleware.dart` و `api_session_token.dart` بيستخدموا السلسلة
// 'UralCash' حرفياً كـ salt. الأماكن دي **ممنوع** تتحول لـ [Brand.name] —
// تغييرها بيبطّل كل الجلسات والتوكنز القائمة على كل الأجهزة. سيبها زي ما هي.
// ═══════════════════════════════════════════════════════════════════════════

/// كل علامة تجارية بيتبني منها منتج مستقل.
///
/// إضافة علامة جديدة: ضيف الـ id هنا في [_known]، وضيف فرع في كل getter
/// تحت، وضيف مجلد أصول تحت `assets/brand/<id>/`.
class Brand {
  Brand._();

  /// مُعرّف العلامة الممرَّر وقت البناء. الافتراضي `uralcash` عشان أي أمر
  /// بناء قديم أو `flutter run` من غير معاملات يفضل شغال زي ما هو.
  static const String id = String.fromEnvironment(
    'APP_BRAND',
    defaultValue: 'uralcash',
  );

  static const bool isUralCash = id == 'uralcash';
  static const bool isPicPos = id == 'picpos';

  /// `false` لو اتمرر مُعرّف علامة مش معروف — بيتفحص عند الإقلاع في
  /// [assertKnownBrand] عشان غلطة كتابة في أمر البناء متعديش لحد العميل
  /// وهي شكلها بناء ناجح.
  static const bool isKnown = isUralCash || isPicPos;

  /// أسماء العلامات المعروفة — لرسالة الخطأ فقط.
  static const List<String> _known = ['uralcash', 'picpos'];

  // ── الاسم ────────────────────────────────────────────────────────────────

  /// الاسم الإنجليزي الظاهر للمستخدم. **مش** اسم الملف التنفيذي (ده في
  /// CMake) ولا الملح التشفيري (ده ثابت حرفي، اقرأ التحذير فوق).
  static const String name = isPicPos ? 'PicPos' : 'UralCash';

  /// الاسم العربي الظاهر للمستخدم.
  static const String nameAr = isPicPos ? 'بيك بوس' : 'يورال كاش';

  // ── الأصول ───────────────────────────────────────────────────────────────

  /// مسار اللوجو في الـ assets.
  ///
  /// ملاحظة: لوجو UralCash لسه في جذر المشروع (`logo.PNG`) ومعلن كده في
  /// pubspec — متنقلش من غير تحديث pubspec والـ ٣ مواضع اللي بتستخدمه.
  static const String logoAsset =
      isPicPos ? 'assets/brand/picpos/logo.png' : 'logo.PNG';

  // ── عزل البيانات ─────────────────────────────────────────────────────────
  //
  // لازم كل منتج يمسك ملف داتابيز ومجلدات خاصة بيه، وإلا لو المنتجين
  // اتثبتوا على نفس الجهاز هيدوسوا على بعض.

  /// بادئة اسم ملف الداتابيز. بيتركّب مع كود الـ flavor في
  /// `getDatabaseFileName()`.
  ///
  /// **حرج:** لـ UralCash لازم تفضل `'uralcash'` بالظبط — أي تغيير معناه إن
  /// التركيبات القائمة تدوّر على ملف مش موجود وتبدأ بداتابيز فاضية.
  static const String dbPrefix = isPicPos ? 'picpos' : 'uralcash';

  /// اسم المجلد المستخدم في المسارات الخاصة بالمنتج (النسخ الاحتياطي،
  /// `C:\ProgramData\<folder>`، ملفات مؤقتة).
  static const String dataFolderName = isPicPos ? 'PicPos' : 'UralCash';

  /// مجلد النسخ الاحتياطي داخل «المستندات» و`APPDATA`.
  ///
  /// **لازم يختلف بين المنتجات:** الاتنين كانوا بيكتبوا في `UralCash_Backups`،
  /// فلو اتثبتوا على نفس الجهاز نسخهم بتتخلط في مجلد واحد بأسماء متشابهة —
  /// استعادة خاطئة تكتب داتابيز منتج فوق التاني. ده خطر بيانات، مش مجرد
  /// تسريب اسم.
  ///
  /// قيمة UralCash لازم تفضل `'UralCash_Backups'` بالظبط، وإلا التركيبات
  /// القائمة «بتفقد» نسخها القديمة (بتدوّر في مجلد جديد فاضي).
  static const String backupFolderName =
      isPicPos ? 'PicPos_Backups' : 'UralCash_Backups';

  // ── المستندات المطبوعة ───────────────────────────────────────────────────

  /// اسم الشركة اللي يُطبع على الفواتير والتقارير **لما العميل ميكونش سجّل
  /// اسم شركته** في الإعدادات (`company_name`).
  ///
  /// أخطر تسريب في المشروع: القيمة كانت مكتوبة صريحة في ~١٧ موضع في مولّدات
  /// المستندات، فأي عميل لعلامة تانية مسجّلش اسمه كان بيطبع فواتيره وعليها
  /// اسم منتج مش بتاعه.
  ///
  /// توحيد: بعض المواضع كانت `'UralCash'` والباقي `'UralCash Market'` — نفس
  /// المنتج كان بيطبع اسمين مختلفين حسب نوع المستند. الحقل الواحد ده بيوحّدهم.
  static const String documentCompanyFallback =
      isPicPos ? 'PicPos' : 'UralCash Market';

  /// اسم قاعدة البيانات والمستخدم الافتراضيين على PostgreSQL (وضع السيرفر).
  ///
  /// **لازم يختلف بين المنتجات:** لو سيرفر PicPos وسيرفر UralCash اشتغلوا على
  /// نفس نسخة PostgreSQL، الاتنين كانوا هيستخدموا قاعدة اسمها `uralcash` —
  /// تصادم بيانات كامل بين منتجين مختلفين لعميلين مختلفين.
  ///
  /// الأثر على UralCash القائم = صفر: القيمة دي **افتراضي للتنصيبات الجديدة**
  /// فقط، وأي تركيب موجود بيقرا القيمة المحفوظة عنده من الإعدادات.
  ///
  /// **حروف صغيرة عن قصد.** PostgreSQL بيحوّل المُعرّفات غير المقتبسة لحروف
  /// صغيرة، فقاعدة اتعملت باسم `PICPOS` بتتخزّن فعلياً كـ `picpos`؛ وبعد كده
  /// أي كود يحاول يوصلها بالكابس لازم يقتبس الاسم في كل استعلام وإلا يفشل.
  /// خلّيه lowercase من الأصل يمنع صنف الأعطال ده بالكامل — وده مستقل عن
  /// طريقة كتابة العلامة في الواجهة (شوف [name]).
  static const String pgIdentifier = isPicPos ? 'picpos' : 'uralcash';

  // ── بيانات المطوّر/المورّد ────────────────────────────────────────────────
  //
  // الشريط ده ظاهر للعميل في ٣ أماكن: تذييل شاشة الدخول، بلوك «عن البرنامج»
  // في الإعدادات، وحوار بوابة السنة المالية.
  //
  // **ده كان أخطر تسريب متبقّي، وفات على كل جولات الفحص.** نمط الفحص في
  // HANDOFF §٣.٤ بيدوّر على `uralcash` حرفياً، و«Ural Technology» و
  // «uraljo.com» و«962797990989» مفيهمش الكلمة دي — فالفحص كان بيقول «صفر
  // تسريب» وهو صادق بالنسبة لنمطه. اتكشف بتشغيل التطبيق وتصوير الشاشة، مش
  // بفحص الـ binary. النمط الموسّع (`ural` بدل `uralcash`) في HANDOFF دلوقتي.
  //
  // PicPos بيسيبها **فاضية عن قصد**، والواجهة بتحذف الشريط بالكامل بدل ما
  // ترسمه فاضي: رقم دعم غلط أسوأ من مفيش رقم — عميل PicPos لو اتصل بـ
  // Ural Technology مش هيعرفوه. لما تتوفّر بيانات PicPos، تعبئتها هنا سطر
  // واحد لكل قيمة والشريط بيرجع يظهر لوحده.
  static const String vendorName = isPicPos ? '' : 'Ural Technology';
  static const String vendorPhone = isPicPos ? '' : '+962797990989';
  static const String vendorEmail = isPicPos ? '' : 'info@uraljo.com';
  static const String vendorWebsite = isPicPos ? '' : 'www.uraljo.com';
  static const String vendorWhatsappUrl =
      isPicPos ? '' : 'https://wa.me/962797990989';
  static const String vendorInstagramUrl =
      isPicPos ? '' : 'https://instagram.com/uraltechnology';
  static const String vendorFacebookUrl =
      isPicPos ? '' : 'https://facebook.com/uraltechnology';

  /// `false` للعلامات اللي مصرّحتش ببيانات مورّد — الواجهة بتحذف الشريط كله.
  static const bool hasVendorInfo = vendorName != '';

  // ── نطاق المنتج ──────────────────────────────────────────────────────────

  /// كود `BusinessProfile` اللي المنتج يقلع بيه على داتابيز جديدة، أو `''`
  /// لو العلامة ملهاش افتراضي خاص (وساعتها الـ `APP_FLAVOR` هو اللي يحدد).
  ///
  /// PicPos منتج «لايت» بتعريفه: نقطة بيع + مخازن + صناديق + تقارير. ده
  /// **نطاق واجهة** — نفس المحرك ونفس الـ schema ونفس حجم الـ binary.
  ///
  /// ── ليه هنا وليس قيمة `AppFlavor` جديدة؟ ─────────────────────────────
  /// اسم ملف الداتابيز مركّب من كود الـ flavor:
  /// `'${Brand.dbPrefix}_${flavor.code}.db'`. فـ `AppFlavor.lite` + بناء بـ
  /// `APP_FLAVOR=lite` كان هيحوّل ملف PicPos من `picpos_unified.db` لـ
  /// `picpos_lite.db` — أي تركيب قائم يدوّر على ملف مش موجود ويبدأ بداتابيز
  /// فاضية. نفس صنف الأعطال اللي القسم ٣.٣ في HANDOFF موجود يمنعه.
  /// وكمان `brand_isolation_test` فيه ٣ تأكيدات شمول على `AppFlavor.values`،
  /// وقيمة جديدة بتفشّلهم — والاختبار ده مش المفروض يتعدّل.
  ///
  /// الافتراضي بيتطبّق على **الإقلاع الأول فقط**؛ بعد كده القيمة المحفوظة في
  /// `settings.business_profile` هي اللي تكسب (شوف `BusinessProfileNotifier`).
  static const String defaultProfileCode = isPicPos ? 'lite' : '';

  /// بيرمي لو الـ `APP_BRAND` الممرَّر مش معروف. بيتنادى عند الإقلاع.
  ///
  /// السبب: `String.fromEnvironment` بترجع أي سلسلة من غير تحقق، فـ
  /// `--dart-define=APP_BRAND=picops` (حروف مقلوبة) كان هيبني بنجاح
  /// وبهوية UralCash — وده بالظبط نوع الخلط اللي الفصل ده موجود يمنعه.
  static void assertKnownBrand() {
    if (!isKnown) {
      throw StateError(
        'APP_BRAND غير معروف: "$id". '
        'العلامات المتاحة: ${_known.join(", ")}. '
        'راجع أمر البناء (--dart-define=APP_BRAND=...).',
      );
    }
  }
}
