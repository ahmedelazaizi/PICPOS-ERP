    0x48, 0x0c, 0xa2, 0x3e, 0xd9, 0x7c, 0x0d, 0xab, 0x7f, 0xc9, 0x78, 0x0d, //
    0xb0, 0x3b, 0xf5, 0x73, 0x53, 0xb5, 0x63,
  ]);

  /// HMAC key of the legacy (pre-v2) invoice integrity signatures.
