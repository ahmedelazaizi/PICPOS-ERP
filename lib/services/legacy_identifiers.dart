/// Internal identifiers inherited from earlier builds — assembled at runtime.
///
/// Why this file exists (owner decision 2026-10-23, see
/// `docs/security/internal-identifier-migration.md`): the PicPos binary must not
/// carry the old product name as readable text, but these values are part of
/// DATA that already exists on users' machines:
///
///  * crypto salts / pepper — change them and every stored invoice hash, session
///    token, device bearer and the legacy DB-key derivation changes;
///  * the OLD secure-storage key names — needed only to find a value written by
///    an earlier build so it can be copied to its PicPos-named key
///    (`StorageKeyMigration`).
///
/// Each value is stored XOR-masked as numbers and decoded on first use, so the
/// exact same bytes are produced without the plain text being in the build.
/// `test/unit/legacy_identifiers_test.dart` pins the SHA-256 of every decoded
/// value to the previous literal's SHA-256. NEVER edit a list below without
/// that test proving the decoded bytes are unchanged.
///
/// Pure Dart (no dart:io / flutter) so any layer can import it.
class LegacyIdentifiers {
  LegacyIdentifiers._();

  static const List<int> _mask = [0x1d, 0x7e, 0xc3, 0x52, 0x9a];

  static String _decode(List<int> masked) => String.fromCharCodes([
        for (var i = 0; i < masked.length; i++) masked[i] ^ _mask[i % _mask.length],
      ]);

  // ── crypto salts / pepper (VALUE MUST STAY BYTE-IDENTICAL) ────────────────

  /// HMAC/hash salt of the legacy shared LAN bearer (`ApiAuthMiddleware`).
  static final String apiTokenSalt = _decode(const [
    0x48, 0x0c, 0xa2, 0x3e, 0xd9, 0x7c, 0x0d, 0xab, 0x7f, 0xdb, 0x4d, 0x37, //
    0xee, 0x24, 0xab,
  ]);

  /// Salt of the legacy derived session-signing key (`ApiSessionToken.deriveKey`).
