    0x48, 0x0c, 0xa2, 0x3e, 0xd9, 0x7c, 0x0d, 0xab, 0x0d, 0xc9, 0x78, 0x1d, //
    0xb6, 0x20, 0xf3, 0x69, 0x07, 0x9c, 0x02, 0xff, 0x6d, 0x0e, 0xa6, 0x20,
    0xc5, 0x6b, 0x4c,
