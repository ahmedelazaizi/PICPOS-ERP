<#
.SYNOPSIS
  Generates the Android UPLOAD keystore(s) for the PicPos apps (audit REL-004).

.DESCRIPTION
  - Creates one PKCS12 keystore per app under -OutDir (default D:\keys\) with keytool.
    The keystores are NEVER written inside the repository (the script refuses an
    -OutDir that resolves inside the repo root).
  - Writes a secret-free template  <app>\android\key.properties.example  for each app.
  - With -WriteKeyProperties it also writes the git-ignored  <app>\android\key.properties
    (this one DOES contain the passwords, exactly like the Flutter docs prescribe).
  - Passwords are read from -StorePassword / -KeyPassword (SecureString) or prompted.
    They are never echoed and never written anywhere except the git-ignored key.properties.

  Release builds of mobile, mobile_pos and mobile_admin FAIL CLOSED when key.properties
  or the keystore is missing (see android/app/build.gradle.kts).

.EXAMPLE
  pwsh tool\gen_android_keystore.ps1
  pwsh tool\gen_android_keystore.ps1 -WriteKeyProperties -Apps mobile_pos

.NOTES
  BACK UP the generated .jks files and passwords offline (password manager + offline copy).
  Losing an upload key means you cannot ship updates over installed APKs.
#>
[CmdletBinding()]
param(
  [string]$OutDir = 'D:\keys',
  [string[]]$Apps = @('mobile', 'mobile_pos', 'mobile_admin'),
  [int]$ValidityDays = 10000,
  [string]$DistinguishedName = 'CN=PicPos, OU=Mobile, O=PicPos, C=EG',
  [securestring]$StorePassword,
  [securestring]$KeyPassword,
  [switch]$WriteKeyProperties,
  [switch]$Force
)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path

function Test-InsideRepo([string]$path) {
  $full = [IO.Path]::GetFullPath($path).TrimEnd('\') + '\'
  return $full.StartsWith($repo.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase)
}
function ConvertTo-Plain([securestring]$s) {
  $b = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($s)
  try { [Runtime.InteropServices.Marshal]::PtrToStringBSTR($b) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($b) }
}

if (Test-InsideRepo $OutDir) {
  throw "Refusing to write keystores inside the repository ($OutDir). Use a path outside $repo."
}
$keytool = (Get-Command keytool -ErrorAction SilentlyContinue)
if (-not $keytool -and $env:JAVA_HOME) { $c = Join-Path $env:JAVA_HOME 'bin\keytool.exe'; if (Test-Path $c) { $keytool = Get-Item $c } }
if (-not $keytool) {
  foreach ($c in @('$env:ProgramFiles\Android\Android Studio\jbr\bin\keytool.exe', '$env:ProgramFiles\Android\Android Studio\jre\bin\keytool.exe')) {
    $c = $ExecutionContext.InvokeCommand.ExpandString($c); if (Test-Path $c) { $keytool = Get-Item $c; break }
  }
}
if (-not $keytool) { throw 'keytool not found. Install a JDK (Android Studio ships one) or set JAVA_HOME.' }
$keytoolPath = if ($keytool.PSObject.Properties['Source']) { $keytool.Source } else { $keytool.FullName }

New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

if (-not $StorePassword) { $StorePassword = Read-Host -AsSecureString 'Keystore password (min 12 chars)' }
if (-not $KeyPassword) { $KeyPassword = Read-Host -AsSecureString 'Key password (Enter = same as keystore password)' }
$sp = ConvertTo-Plain $StorePassword
if ($sp.Length -lt 12) { throw 'Keystore password must be at least 12 characters.' }
$kp = ConvertTo-Plain $KeyPassword
if ([string]::IsNullOrEmpty($kp)) { $kp = $sp }

foreach ($app in $Apps) {
  $androidDir = Join-Path $repo "$app\android"
  if (-not (Test-Path $androidDir)) { Write-Warning "skip $app : $androidDir not found"; continue }
  $alias = "picpos-$($app -replace '_', '-')-upload"
  $jks = Join-Path $OutDir "$app-upload.jks"
  if ((Test-Path $jks) -and -not $Force) {
    Write-Host "keystore exists, kept: $jks (use -Force to replace - this destroys the old key!)"
  } else {
    if (Test-Path $jks) { Remove-Item $jks -Force }
    & $keytoolPath -genkeypair -v -storetype PKCS12 -keystore $jks -alias $alias `
      -keyalg RSA -keysize 4096 -validity $ValidityDays -dname $DistinguishedName `
      -storepass $sp -keypass $kp
    if ($LASTEXITCODE -ne 0) { throw "keytool failed for $app (exit $LASTEXITCODE)" }
    Write-Host "created $jks (alias $alias)"
  }

  $storeFileLine = ($jks -replace '\\', '/')
  $template = @"
# Template - copy to key.properties (git-ignored) and fill in the passwords.
# Generated by tool/gen_android_keystore.ps1. NEVER commit real values.
storeFile=$storeFileLine
storePassword=<keystore password>
keyAlias=$alias
keyPassword=<key password>
"@
  [IO.File]::WriteAllText((Join-Path $androidDir 'key.properties.example'), $template.Replace("`r`n", "`n") + "`n", (New-Object Text.UTF8Encoding $false))
  Write-Host "wrote $app\android\key.properties.example (no secrets)"

  if ($WriteKeyProperties) {
    $real = $template.Replace('<keystore password>', $sp).Replace('<key password>', $kp)
    $target = Join-Path $androidDir 'key.properties'
    [IO.File]::WriteAllText($target, $real.Replace("`r`n", "`n") + "`n", (New-Object Text.UTF8Encoding $false))
    Write-Host "wrote $app\android\key.properties (git-ignored, contains secrets)"
  }
}
Write-Host ''
Write-Host "Done. Back up $OutDir offline. Verify: cd <app>; flutter build apk --release"
Write-Host 'Then:  apksigner verify --print-certs build\app\outputs\flutter-apk\app-release.apk'
