// Internal-identifier migration — REAL SQLCipher compatibility check.
//
// A database encrypted by an earlier build with the *fallback* key stored in
// secure storage under the OLD key name must still open through the real
// `openConnection()` path after the rename, and the key must end up under the
// PicPos name (old name removed after a verified copy).
//
// Skips clearly without SQLCipher (plain `flutter test`). Real run:
//   powershell -NoProfile -ExecutionPolicy Bypass -File tool\run_sqlcipher_tests.ps1 test/integration/db_key_old_fallback_name_real_test.dart
//
// Everything lives in a temp folder (fake path provider + mock secure storage);
// no user file is touched.
import 'dart:io';

import 'package:drift/drift.dart'
    show OpeningDetails, QueryExecutor, QueryExecutorUser;
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;
import 'package:path_provider_platform_interface/path_provider_platform_interface.dart';
import 'package:picpos_erp/data/database/connection_io.dart';
import 'package:picpos_erp/services/db_key_boot.dart';
import 'package:picpos_erp/services/db_key_names.dart';
import 'package:picpos_erp/services/db_key_types.dart';
import 'package:picpos_erp/services/legacy_device_seed.dart';
import 'package:picpos_erp/services/sqlcipher_engine.dart';

import '../helpers/sqlcipher_real.dart';

class _FakePathProvider extends PathProviderPlatform {
  _FakePathProvider(this.docs);
  final String docs;
  @override
  Future<String?> getApplicationDocumentsPath() async => docs;
}

class _User extends QueryExecutorUser {
  @override
  int get schemaVersion => 7;
  @override
  Future<void> beforeOpen(QueryExecutor e, OpeningDetails d) async {}
}

Future<({int settings, int users, int userVersion})> _openAndRead() async {
  final ex = openConnection();
  try {
    await ex.ensureOpen(_User());
    return (
      settings: await scalarInt(ex, 'SELECT count(*) FROM settings;'),
      users: await scalarInt(ex, 'SELECT count(*) FROM users;'),
      userVersion: await scalarInt(ex, 'PRAGMA user_version;'),
    );
  } finally {
    await ex.close();
  }
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  const engine = NativeSqlCipherEngine();
  const storage = FlutterSecureStorage();
  final savedProvider = LegacyDeviceSeed.deviceIdProvider;

  late Directory docs;
  late File db;

  // A 64-hex fallback key like the one generated by earlier builds.
  const fallbackHex =
      '0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef';
  const fallback = DbKey(DbKeyKind.legacyFallback, fallbackHex);

  setUp(() {
    docs = Directory.systemTemp.createTempSync('picpos_oldname_real_');
    PathProviderPlatform.instance = _FakePathProvider(docs.path);
    // No device id ⇒ the stored fallback key is the only legacy candidate.
    LegacyDeviceSeed.deviceIdProvider = () async => null;
    db = File(p.join(docs.path, getDatabaseFileName()));
    DbKeyBoot.resetMemo();
    DbKeyBoot.lastOutcome = null;
    DbKeyBoot.factoryOverride = null;
  });

  tearDown(() {
    LegacyDeviceSeed.deviceIdProvider = savedProvider;
    DbKeyBoot.processIdOverride = null;
    DbKeyBoot.resetMemo();
    try {
      docs.deleteSync(recursive: true);
    } catch (_) {}
  });

  test('DB encrypted with the fallback key under the OLD storage name opens; '
      'key is moved to the PicPos name', () async {
    if (!await requireSqlCipher()) return;

    await createDb(db, fallback, userVersion: 7, settingsRows: 3);
    expect(looksPlain(db), isFalse);
    final bytesBefore = await db.readAsBytes();

    // Simulate the earlier build's secure-storage state: ONLY the old name.
    FlutterSecureStorage.setMockInitialValues(
        {DbKeyNames.legacyFallbackOld: fallbackHex});

    DbKeyBoot.processIdOverride = 'boot-old-name-1';
    final r = await _openAndRead();
    expect((r.settings, r.users, r.userVersion), (3, 1, 7));

    expect(await storage.read(key: DbKeyNames.legacyFallback), fallbackHex);
    expect(await storage.read(key: DbKeyNames.legacyFallbackOld), isNull);
    expect(await engine.canOpen(db, fallback), isTrue);
    // No automatic re-keying: the file itself is unchanged by opening/reading.
    expect(await engine.canOpen(db, fallback), isTrue);
    expect((await db.readAsBytes()).length, bytesBefore.length);

    // Next boot (key now only under the PicPos name) opens it the same way.
    DbKeyBoot.resetMemo();
    DbKeyBoot.processIdOverride = 'boot-old-name-2';
    final r2 = await _openAndRead();
    expect((r2.settings, r2.users, r2.userVersion), (3, 1, 7));
  });
}
