//
// ═══ لماذا وُجد هذا الحارس ═══
//
// العلاقةُ بين النسختين كانت محروسةً **بتعليقٍ في رأس الملفّ** لا غير:
// «منسوخ من … أيُّ إصلاحٍ منطقيٍّ يتصلّح في المصدر أوّلاً ثمّ patch». وتعليقٌ
// لا يُفشِل بناءً ولا اختباراً — فانحرافُ أحدِ التوأمين عن الآخر كان يمرّ
// صامتاً بحكم التعريف.
//
// وازداد الخطرُ حين نزل تصميمُ PicPos (2026-08-21) فباعد **الشكلَ** عمداً:
// بطاقةٌ رئيسيّةٌ بالمعادلة بدل ستِّ بطاقاتٍ متساوية. وبعد أن صار التباعدُ
// الظاهريُّ مشروعاً، لم يعد اختلافُ الملفّين قرينةً على شيء — فوجب أن
// يُقاس **المنطقُ** وحدَه صراحةً.
//
// ═══ ما يُقاس ولماذا هذه البنود بالذات ═══
//
// ١) كودُ الحجب: لو حُجبت إحدى النسختين بكودٍ آخرَ (أو بلا كود) لرأى مستخدمٌ
//    على فورك مبالغَ يحجبها الفوركُ الآخرُ عنه — والصلاحيةُ واحدةٌ في القاعدة.
// ٢) تعريفُ «المحصّل»: `totalPaid + receiptVouchersTotal` (‏Issue 10). لو
//    أسقط أحدُهما سنداتِ القبض لاختلف رقمُ التحصيل بين الفوركين على نفس
//    البيانات — وهو الفرقُ الذي لا يظهر إلا في شكوى عميل.
// ٣) مجموعةُ المقاييس: غيابُ «صافي المبيعات» أو «إجمالي المرتجعات» من أحدهما
//    يعني أن فورقاً يعرض إجمالاً بلا ما يفسّره.
//
// ولا يُقاس هنا الشكل: لا حجمٌ ولا لونٌ ولا عددُ بطاقات. تباعدُها مقصود.
import 'dart:io';
import 'package:flutter_test/flutter_test.dart';

void main() {
  const uralcash =
      'lib/presentation/screens/widgets/sales_invoices/sales_summary_cards.dart';
  const picpos =
      'lib/presentation/sales_invoices_picpos/screens/sales_summary_cards.dart';

  String read(String p) {
    final f = File(p);
    expect(f.existsSync(), isTrue, reason: 'الملفُّ $p غيرُ موجود');
    return f.readAsStringSync();
  }

  late final Map<String, String> twins = {
    'UralCash': read(uralcash),
    'PicPos': read(picpos),
  };

  test('كلا التوأمين يحجب المبالغ بـ`sales_amounts_view` عينِه', () {
    twins.forEach((name, src) {
      expect(src.contains('PermissionCodes.salesAmountsView'), isTrue,
          reason: '$name لا يحجب مبالغَ الإجماليات — أو يحجبها بكودٍ آخر. '
              'الصلاحيةُ واحدةٌ في القاعدة، فلا يصحّ أن يرى مستخدمٌ على فورك '
              'ما يُحجَب عنه على الآخر');
      expect(src.contains('buildMaskedAmountKpiCard'), isTrue,
          reason: '$name فقد الدالّةَ المحروسة — '
              '`task_9_sales_documents_permission_gates_test` ينادي '
              'الاسمَ نفسَه من الفوركين معاً');
    });
  });

  test('«المحصّل» = مدفوعاتُ الفواتير + سنداتُ القبض في الاثنين (Issue 10)', () {
    twins.forEach((name, src) {
      expect(src.contains('totalPaid + receiptVouchersTotal'), isTrue,
          reason: '$name يحسب المحصَّلَ بغير هذا التعريف. إسقاطُ سندات القبض '
              'يجعل رقمَ التحصيل يختلف بين الفوركين على نفس البيانات — '
              'فرقٌ لا يظهر إلا في شكوى عميل');
    });
  });

  test('مجموعةُ المقاييس الستّة حاضرةٌ في الاثنين', () {
    // الصياغةُ نفسُها لا معناها فقط: نصٌّ مختلفٌ يعني عمودَ تقريرٍ مختلفاً
    // في عينِ المستخدم ولو تطابق الحساب.
    const metrics = [
      'إجمالي المبيعات (شامل الضريبة)',
      'المحصّل',
      'المتبقي',
      'إجمالي المرتجعات',
      'صافي المبيعات',
      'عدد الفواتير',
    ];
    twins.forEach((name, src) {
      for (final m in metrics) {
        expect(src.contains(m), isTrue,
            reason: '$name لا يعرض «$m» — فورقٌ يعرض إجمالاً بلا ما يفسّره');
      }
    });
  });
}
