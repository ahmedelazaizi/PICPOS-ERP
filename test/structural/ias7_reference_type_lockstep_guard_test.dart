// حارسُ العقد: كلُّ نوعِ مرجعٍ يكتبه محرّكُ الأصول **مصنَّفٌ** في قائمة
// التدفّقات النقديّة — لا نوعَ يُكتَب ولا يُصنَّف.
//
// ═══ فئةُ العطب ═══
//
// تصنيفُ التدفّق له **طرفان** لا يعرف أحدُهما الآخر:
//
//   ‏١) المحرّكُ — `fixed_assets_dao_ext.dart` — يكتب `referenceType` نصّاً
//      حرفيّاً في كلِّ نداءِ `createJournalEntry`.
//   ‏٢) والتقريرُ — `getCashFlowStatement` — يرشّح على مجموعةٍ من النصوص
//      ليفصل التشغيليَّ (‏IAS 7.14) عن الاستثماريِّ (‏IAS 7.16).
//
// 🔴 **ووقع فعلاً:** انحرف الطرفان. التقريرُ كان يرشّح على
// `'asset_acquisition'` و`'asset_disposal'` — **ولا يكتب المستودعُ كلُّه
// أيّاً منهما**؛ والمحرّكُ يكتب `'fixed_asset'` و`'fixed_asset_disposal'`.
//
// فكلُّ شراءِ أصلٍ أو بيعِه نقداً وقع في القِسم الخطأ **مرّتين**: لم
// يُستثنَ من التشغيليّة فاحتُسب فيها، ولم يظهر في الاستثماريّة فقُرئت
// صفراً. مقيسٌ: ١٣٠٠٠٠ شراءً و٣٠٠٠٠ بيعاً ⇒ الاستثماريّةُ `0.0`
// والتشغيليّةُ خارجاً `130000.0`.
//
// وصافي التغيّر في النقديّة بقي **صحيحاً** — المبلغُ لم يضِعْ بل انتقل —
// فلم يمسكه أيُّ فحصِ اتّزانٍ ولا أيُّ مصالحة. والمكسورُ هو الفصلُ بين
// الأقسام، وهو غرضُ القائمة الأوّل.
//
// ═══ لماذا حارسُ بنيةٍ لا اختبارُ سلوك ═══
//
// `ias7_fixed_asset_cashflow_classification_test.dart` يقيس السلوكَ
// للاقتناء والاستبعاد، وهو الاختبارُ الذي رأى العطبَ أحمر. لكنّه يغطّي
// **الحركتَين اللتَين نعرفهما اليوم** فقط: يُضاف غداً `asset_impairment`
// أو `asset_writeoff` إلى المحرّك، فيُكتَب نوعٌ جديدٌ لا يعرفه التقريرُ
// ويعود العطبُ نفسُه صامتاً — واختبارُ السلوك يبقى أخضرَ لأنّه لا يعلم
// بوجود النوع الجديد.
//
// فهذا الحارسُ **يشتقُّ** ما يكتبه المحرّك من الملفِّ نفسِه — لا من قائمةٍ
// يدويّةٍ أنسخُها وتشيخ — ويرفض أيَّ نوعٍ غيرِ مصنَّف.

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:picpos_erp/data/database/database.dart';

/// المحرّكُ الذي يكتب أنواعَ مراجع الأصول.
const String _enginePath =
    'lib/data/database/daos/fixed_assets_dao_ext.dart';

/// أنواعٌ يكتبها المحرّكُ ولا رِجْلَ نقدٍ لها إطلاقاً، فلا تُصنَّف في
/// أيِّ قسمٍ من القائمة — وغيابُها عن القائمتَين **صحيحٌ لا سهو**.
///
/// الإهلاكُ: مدين `6213` مصروفُ إهلاك / دائن مجمَّعُ الإهلاك. وترشيحا
/// القائمة كلاهما مقيَّدان بحسابات النقد/البنك، فالقيدُ يُقرأ صفراً في
/// الطرفَين. والقائمةُ تُبنى بالمنهج **المباشر** (جمعُ رِجْلِ النقد) لا
/// غيرِ المباشر (‏IAS 7.20: الربحُ ثمّ إضافةُ غير النقديِّ عكسيّاً)، فلا
/// إضافةَ عكسيّةً للإهلاك تُصنَع هنا أصلاً.
///
/// وهذا **مقيسٌ** لا مفترَضٌ في
/// `ias7_fixed_asset_cashflow_classification_test.dart`: يُشغّل الإهلاكَ
/// الحقيقيَّ ثمّ يؤكّد أنّ لا رِجْلَ له في شجرة النقديّة وأنّ الأقسامَ
/// الثلاثةَ لم تتحرّك بحرف.
const Set<String> _nonCashRefTypes = {'asset_depreciation'};

/// يستخرج كلَّ `referenceType: '<value>'` من نصِّ المحرّك.
Set<String> _refTypesWrittenBy(String source) =>
    RegExp(r"referenceType:\s*'([a-z0-9_]+)'")
        .allMatches(source)
        .map((m) => m.group(1)!)
        .toSet();

void main() {
  late Set<String> written;

  setUpAll(() {
    final engine = File(_enginePath);
    expect(engine.existsSync(), isTrue,
        reason: 'انتقل المحرّك؟ فحدِّث [_enginePath] — وإلّا صار الحارسُ '
            'يقرأ فراغاً ويمرّ أخضرَ على لا شيء');
    written = _refTypesWrittenBy(engine.readAsStringSync());
  });

  test('التجهيزة: الاشتقاقُ التقط أنواعاً فعلاً', () {
    // ⚠️ بلا هذا التوكيد يكون النمطُ المعطوبُ حارساً أخضرَ دائماً: مجموعةٌ
    // فارغةٌ تعبر كلَّ فحصٍ أدناه. والرقمُ حدٌّ أدنى لا مساواةٌ — إضافةُ
    // نوعٍ جديدٍ يجب أن يُسقط الفحصَ المعنيَّ أدناه لا هذا.
    expect(written.length, greaterThanOrEqualTo(5),
        reason: 'المحرّكُ يكتب خمسةَ أنواعٍ على الأقلّ (اقتناءٌ · إهلاكٌ · '
            'استبعادٌ · نقلٌ · إعادةُ تقييم) — فقلّةُ المطابقات تعني نمطاً '
            'انحرف عن صياغة النداء لا محرّكاً تغيّر: $written');

    // مرساةٌ على قيمتَين نعرف أنّهما مكتوبتان — تمسك نمطاً يطابق شيئاً
    // آخرَ غيرَ ما نقصد.
    expect(written, contains('fixed_asset'));
    expect(written, contains('asset_depreciation'));
  });

  test('كلُّ نوعٍ يكتبه المحرّك إمّا مصنَّفٌ في قسمٍ وإمّا معلَنٌ غيرَ نقديّ',
      () {
    final classified = {
      ...kInvestingJeReferenceTypes,
      ...kFinancingJeReferenceTypes,
      ..._nonCashRefTypes,
    };
    final unclassified = written.difference(classified);

    expect(unclassified, isEmpty,
        reason: 'أنواعٌ يكتبها المحرّكُ ولا يعرفها التقرير: $unclassified\n'
            'لكلِّ واحدٍ منها قرارٌ واجبٌ — إن كان يحمل نقداً فأضِفْه إلى '
            '[kInvestingJeReferenceTypes] (أو التمويليّة)، وإن كان غيرَ '
            'نقديٍّ إطلاقاً فأضِفْه إلى [_nonCashRefTypes] مع بيانِ '
            'رِجْلَيه. وتركُه بلا تصنيفٍ يعني أنّه يُحتسَب **تشغيليّاً** '
            'بصمتٍ — وهو عينُ العطب الذي وُلد هذا الحارسُ منه.');
  });

  test('لا نوعَ مصنَّفاً استثماريّاً بلا كاتبٍ في المحرّك', () {
    // الطرفُ المقابل: قيمةٌ في قائمة التقرير لا يكتبها شيءٌ هي **بالضبط**
    // شكلُ العطب الأصليّ — `'asset_acquisition'` عاشت هنا سنةً تُرشِّح
    // على صفر. فوجودُها في القائمة لا يكفي؛ لا بدّ من كاتب.
    final phantom = kInvestingJeReferenceTypes.difference(written);
    expect(phantom, isEmpty,
        reason: 'أنواعٌ يرشّح عليها التقريرُ ولا يكتبها المحرّك: $phantom\n'
            'هذه ترشيحٌ على فراغٍ — وهو عينُ `asset_acquisition` '
            'و`asset_disposal` قبل الإصلاح. احذِفْها أو صحِّحْ هجاءَها.');
  });

  test('التشغيليّةُ هي الباقي — لا تقاطعَ بين الأقسام', () {
    // نوعٌ في القائمتَين معاً يُحتسَب مرّتين في المجموع، فينكسر اتّزانُ
    // «الأقسامُ الثلاثةُ تجمع إلى صافي التغيّر».
    final overlap =
        kInvestingJeReferenceTypes.intersection(kFinancingJeReferenceTypes);
    expect(overlap, isEmpty,
        reason: 'الاستثماريّةُ والتمويليّةُ تتقاطعان في $overlap — '
            'والحركةُ تُحتسَب مرّتين');

    final nonCashLeak =
        _nonCashRefTypes.intersection(kInvestingJeReferenceTypes);
    expect(nonCashLeak, isEmpty,
        reason: 'نوعٌ معلَنٌ غيرَ نقديٍّ ومصنَّفٌ استثماريّاً معاً: '
            '$nonCashLeak — القرارُ واحدٌ لا اثنان');
  });
}
