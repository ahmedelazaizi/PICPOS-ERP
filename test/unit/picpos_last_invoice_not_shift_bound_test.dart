// «آخر فاتورة» فوق السلة ليست محدودةً بنافذة الوردية.
//
// ── البلاغ الميدانيّ (المالك، 2026-08-15) ─────────────────────────────────
// «رقمُ آخر فاتورة لا تظهر رقمَها فوق السلة — راجع منطقها.» وحين سُئل متى:
// «يظهر بعد البيع فقط، ويختفي مع ورديةٍ جديدة.»
//
// ── والجذرُ مقيسٌ في توثيق الملفّ نفسِه — وهو **متناقض** ─────────────────
// `picpos_last_invoice_provider.dart` كان يكتب:
//
//     final shift = await …getCurrentOpenShift(userId);
//     since = shift?.startTime;
//
// وتعليقُه يقول في موضعٍ «أحدث فاتورة داخل نافذة الوردية المفتوحة»، ويقول في
// موضعٍ آخرَ بعده بأربعة أسطر: «فقبل أوّل بيعة في الجلسة الترويسةُ بتعرض آخر
// فاتورة للحساب ده مهما كان التِلّ اللي باعها».
//
// والوعدان لا يجتمعان: ورديةٌ فُتحت للتوّ لا فاتورةَ فيها، فالحدُّ يُفرغ
// الترويسةَ حتماً حتى أوّل بيعة. وهو بالضبط ما رآه المالك.
//
// ── والعنوانُ يحسم أيَّ الوعدَين يبقى ────────────────────────────────────
// الترويسةُ مكتوبٌ عليها «آخر فاتورة» لا «آخر فاتورة في الوردية»، والحاجةُ
// المذكورةُ في مواصفة الملفّ هي إعادةُ طباعة آخر فاتورةٍ للكاشير. فالحدُّ
// بالمستخدم يبقى، وحدُّ الوردية يسقط.
//
// ── ولماذا حارسٌ بنيويّ ──────────────────────────────────────────────────
// السلوكُ هنا `StreamProvider` يقرأ قاعدةً ووردياتٍ ومتحكّمَ دفع؛ وقياسُه
// سلوكياً يحتاج شجرةَ ودجتاتٍ وقاعدةً حيّة. والعطبُ نفسُه **سطرٌ واحد**
// يسهل أن يعود مع أوّل من يقرأ التعليقَ القديم. فالحارسُ يقف على السطر.

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

const _path = 'lib/presentation/pos_picpos/providers/'
    'picpos_last_invoice_provider.dart';

String _stripComments(String src) => src
    .split('\n')
    .map((l) {
      final i = l.indexOf('//');
      return i == -1 ? l : l.substring(0, i);
    })
    .join('\n');

void main() {
  late String code;

  setUpAll(() {
    final f = File(_path);
    expect(f.existsSync(), isTrue, reason: 'المزوّدُ انتقل — حدِّث الحارس');
    code = _stripComments(f.readAsStringSync());
  });

  test('لا تُحدَّد «آخر فاتورة» ببداية الوردية', () {
    // ⚠️ التجريدُ من التعليقات مقصود: شرحُ سبب الإزالة مكتوبٌ في الملفّ
    // ويذكر `getCurrentOpenShift` نصّاً — وبلا التجريد يسقط الحارسُ على
    // وثائقه هو. (‏نفسُ درسِ «التعليقُ ليس كوداً».)
    expect(
      code.contains('getCurrentOpenShift'),
      isFalse,
      reason: 'عاد حدُّ الوردية ⇒ الترويسةُ تفرغ حتى أوّل بيعة في كلّ وردية',
    );
  });

  test('والحدُّ بالمستخدم يبقى — وإلا عُرضت فاتورةُ غيرِه', () {
    // المواصفةُ صريحة: «تظهرله بتاعته — مش تستدعي بتاع … مستخدم تاني».
    expect(code.contains('watchLastInvoiceForUser'), isTrue);
    expect(code.contains('authProvider'), isTrue);
  });
}
