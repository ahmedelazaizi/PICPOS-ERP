// ═══════════════════════════════════════════════════════════════════════════
// سعر وحدة التعبئة — شوال السكر مش لازم يساوي سعر الكيلو × ٥٠.
// ═══════════════════════════════════════════════════════════════════════════
//
// بلاغ مختبِر: «تعديل السعر لكل وحدة تعبئة… شوال سكر السعر له غير لما يكون
// بالكيلو / إضافة مهمة جداً يوجد نقص فيها».
//
// القدرة كانت موجودة من الآخر للآخر: `product_units.sale_price` عمود حقيقي،
// والبيع السريع بتحترمه فعلاً (cart_item_tile.dart:673 و cart_controller:1180).
// النقص كان في نموذج الصنف وحده: صفّ الوحدة فيه اسم ومعامل وباركود بس —
// **ومفيش حقل سعر** — والحفظ بيكتب `سعر الصنف × المعامل` دايماً.
//
// وكان دائرياً كمان: التحميل عند الفتح بيتجاهل `u.salePrice` المخزّن، والحفظ
// بيمسح الوحدات ويعيد إدراجها بالسعر المشتق. فأي سعر مخصّص — حتى لو اتحطّ في
// القاعدة مباشرةً — بيضيع مع أول فتح وحفظ للصنف.
//
// القاعدة اتجمّعت في دالة واحدة لأنها بتتكرّر في تلات مواضع: الحفظ في نموذج
// التعديل، والحفظ في نموذج الإضافة، و**حِمل السيرفر** في نموذج الإضافة. لو
// اختلف أي واحد فيهم، السيرفر يخزّن سعراً والعميل غيره وأول DeltaPull يدهس
// سعر المستخدم.
// ═══════════════════════════════════════════════════════════════════════════

import 'package:flutter_test/flutter_test.dart';
import 'package:picpos_erp/presentation/widgets/dialogs/product_form_helpers.dart';

void main() {
  double resolve(double? typed, double base, double factor) =>
      ProductFormHelpers.resolveUnitSalePrice(
        typedPrice: typed,
        baseSalePrice: base,
        factor: factor,
      );

  group('المُدخَل يفوز', () {
    test('شوال ٥٠ كيلو بسعر جملة أقل من الاشتقاق', () {
      // كيلو السكر بـ٢٠، والشوال بـ٩٠٠ جملةً (مش ١٠٠٠).
      expect(resolve(900, 20, 50), 900,
          reason: 'ده جوهر البلاغ — الاشتقاق كان بيفرض ١٠٠٠');
    });

    test('سعر مُدخَل أعلى من الاشتقاق برضو بيُحترم', () {
      // وحدة تجزئة صغيرة بهامش أعلى.
      expect(resolve(25, 20, 1), 25);
    });
  });

  group('فاضي = اشتق (السلوك القديم كـسلوك افتراضي)', () {
    test('null بيشتق', () {
      expect(resolve(null, 20, 50), 1000);
    });

    test('صفر بيشتق — مش سعر مجاني بالغلط', () {
      expect(resolve(0, 20, 50), 1000,
          reason: 'حقل اتساب فاضي أو اتكتب فيه صفر مش نية بيع ببلاش');
    });

    test('سالب بيشتق', () {
      expect(resolve(-5, 20, 50), 1000);
    });

    test('الوحدة الأساسية (معامل ١) بتشتق سعر الصنف نفسه', () {
      expect(resolve(null, 20, 1), 20);
    });
  });

  test('التلات مواضع لازم تتفق — نفس المُدخَلات نفس الناتج', () {
    // الحفظ المحلي وحِمل السيرفر بيندهوا نفس الدالة، فاتفاقهم مضمون بالبناء.
    // الاختبار ده بيوثّق النية: لو حد فكّ التجميع تاني وكتب القاعدة يدوياً في
    // موضع، ده السطر اللي بيقول ليه ده غلط.
    const typed = 900.0, base = 20.0, factor = 50.0;
    final local = resolve(typed, base, factor);
    final payload = resolve(typed, base, factor);
    expect(local, payload,
        reason: 'اختلافهم معناه إن DeltaPull بيدهس سعر المستخدم');
  });
}
