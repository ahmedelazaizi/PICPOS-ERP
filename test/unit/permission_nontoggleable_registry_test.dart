// test/unit/permission_nontoggleable_registry_test.dart
//
// `PermissionCodes.nonToggleable` و`PermissionEnforcementRegistry.
// knownUnenforced` لازم يفضلوا مجموعتين منفصلتين تماماً: كود واحد إما لسه
// محتاج إنفاذ (knownUnenforced) وإما مستحيل يتحلّ بإنفاذ (nonToggleable) —
// مش الاتنين مع بعض (Task 5، 2026-08-01).
//
// الاكتمال (إن كل كود بلا إنفاذ حقيقي موجود في واحدة من المجموعتين، ومفيش
// كود ضايع من التتبّع بالكامل) بيتفحص في
// `permission_enforcement_coverage_test.dart` اللي بيمسح `lib/` فعلياً.
// الاختبار ده بيركّز على حاجة تانية: إن المجموعتين ما بيتقاطعوش، وإن حجمهم
// ثابت كنتيجة معروفة للفرز — لو كود اتشال من واحدة من غير ما يتضاف
// للتانية بالسبب الصحيح، بيختفي من التتبّع بالكامل، وده بالظبط نوع
// الانزلاق اللي خلّى ٨٠ كود يفضلوا من غير رقابة لحدّ ما حصل السويب.
import 'package:flutter_test/flutter_test.dart';
import 'package:picpos_erp/core/permissions/permission_codes.dart';
import 'package:picpos_erp/core/permissions/permission_enforcement_registry.dart';

void main() {
  test('nonToggleable و knownUnenforced ما بيتقاطعوش', () {
    final nonToggleable = PermissionCodes.nonToggleable.keys.toSet();
    const knownUnenforced = PermissionEnforcementRegistry.knownUnenforced;

    final overlap = nonToggleable.intersection(knownUnenforced).toList()
      ..sort();

    expect(
      overlap,
      isEmpty,
      reason:
          'أكواد مسجّلة في المجموعتين مع بعض — كل كود لازم يبقى في واحدة '
          'بس (إما لسه محتاج إنفاذ، أو مستحيل يتحلّ):\n'
          '${overlap.join('\n')}',
    );
  });

  // ٣٣ (الفرز) → ٣٤ (دفعة ١١: `dashboard_sales_total` اتنقل هنا لأن مفيش
  // كارت «إجمالي مبيعات» منفصل — نفس كارت `dashboard_sales_today` بفلتر
  // فترة أوسع، فتشغيله كان هيتطلّب اختراع ودجت جديدة).
  //
  // ── ٣٤ → ٤٤ (2026-08-13): حذفُ خدمةٍ ميّتة ──────────────────────────────
  // `lib/services/role_based_sidebar_service.dart` (٢١٢ سطراً) كان **بصفر
  // مستوردين** في `lib/` و`test/` و`tool/` — مقيسٌ لا مفترَض. ومع ذلك كان
  // `permission_enforcement_coverage_test` يمسح `lib/` نصّاً، فيرى الأكوادَ
  // العشرةَ المذكورةَ فيه **وحدَه** ويعدّها منفَّذة.
  //
  // فكانت عشرةُ مفاتيحَ تظهر للمدير في شاشة الصلاحيات ولا تفعل شيئاً — وهو
  // بعينه بلاغُ «بغيّر صلاحية ومش بيحصل حاجة» الذي وُجد هذا السجلُّ لأجله.
  //
  // ولا واحدٌ منها ثغرةٌ حقيقية: تسعةٌ شاشاتُها **مبوّبةٌ بكودٍ آخرَ فعلاً**
  // في `screenPermissionMap` (تكرارٌ اسميّ = بكت «ب»)، والعاشرُ
  // (`warehouses_view`) لا شاشةَ له في التطبيق أصلاً (= بكت «ج»).
  //
  // ⚠️ ولذلك **لا** تُنقَل إلى `knownUnenforced`: ذاك سجلُّ «لسه محتاج
  // إنفاذ» وهو فارغٌ منذ دفعة ١٢، وإضافتُها إليه كانت ستقول زوراً إن ثمّة
  // عشرَ ثغراتٍ تنتظر العمل.
  // ── ٤٣ بعد دمج الفرعَين (2026-08-18) ────────────────────────────────────
  // فرعان عدّلا هذا الرقمَ متوازيَين فتعارض النصّان: فرعُ الصلاحيات رفعه إلى
  // ٤٤ (‏+١٠ أكوادٍ كانت مربوطةً بخدمةٍ ميّتة حُذفت 2026-08-13)، وفرعُ
  // الطاولات خفضه إلى ٣٣ (‏−`tables_print_bill` الذي انتقل إلى
  // `knownUnenforced` لأن ميزتَه صارت مخطَّطةً لا مستحيلة).
  //
  // والرقمُ هنا **مقيسٌ من الملفّ المدموج لا محسوبٌ من الطرفَين**: ٤٤ − ١ = ٤٣،
  // وتأكّد بعدّ المداخل فعلاً وبالتحقّق أن `tables_print_bill` خرج.
  // ── ٤٢ بعد فصل عروض الأسعار ─────────────────────────────────────────────
  // `quotes_view` كان هنا لأن عروض الأسعار تبويبٌ داخل فواتير البيع المبوّبة
  // بـ`sales_view`. صارت شاشةً مستقلّةً مبوّبةً بـ`quotes_view` نفسه في
  // `screenPermissionMap`، فخرج الكودُ من السجلّ لأنه صار مُنفَّذاً فعلاً.
  test('nonToggleable فيه ٤٢ كود بالظبط (نتيجة الفرز — بكت ب+ج+د)', () {
    expect(
      PermissionCodes.nonToggleable.length,
      42,
      reason:
          'عدد الأكواد المستحيل حلّها بإنفاذ لازم يفضل ٤٢ (٣٤ من الفرز + ١٠ '
          'كانت مربوطةً بخدمةٍ ميّتة اتحذفت 2026-08-13، ناقص tables_print_bill '
          'اللي خرج في Task 8، وناقص quotes_view اللي صار مُنفَّذاً بشاشة '
          'عروض الأسعار المستقلّة) — لو اتغيّر، يبقى فيه كود اتضاف/اتشال من غير '
          'ما التريّاج يتراجع',
    );
    expect(PermissionCodes.nonToggleable.containsKey(PermissionCodes.quotesView),
        isFalse,
        reason: 'quotes_view مُنفَّذ الآن على شاشة عروض الأسعار');
  });

  // مسار الانكماش (كل رقم = دفعة إنفاذ حقيقية اتنفّذت):
  //   ٤٧ (الفرز، Task 5) → ٤٠ (٦أ) → ٣٣ (٦ب) → ٢٥ (٧) → ١٩ (٨: الأصناف)
  //   → ١٣ (٩: المستندات والطباعة) → ٧ (١٠: الإعدادات والنظام)
  //   → ٣ (١١: لوحة التحكم — ٣ اتنفّذوا وواحد اتنقل لـnonToggleable)
  //   → ٠ (١٢: التقارير — آخر تلات أكواد في السجل)
  //
  // الرقم ده كان فاضل ٤٧ من Task 5 لحد دفعة ٨ — يعني الاختبار كان أحمر من
  // غير ما حد ياخد باله عبر تلات دفعات، لأن الدفعات كانت بتشغّل اختباراتها
  // المستهدفة بس والبوابة الكاملة اتأجّلت. الدرس: أي دفعة بتشيل من السجل
  // لازم تحدّث الرقم ده في نفس الكوميت.
  // خلص فاضياً بدفعة ١٢. Task 8 (2026-08-16) ضاف كودين جداد لـmasterList
  // (تصنيف الطاولات) بلا إنفاذ بعد — مش بقية شغل قديم: 'tables_discount'
  // (زرّ الخصم لسه ما بُنيش، تبنيه المهامّ ٩-١٢) و'tables_print_bill'
  // (خرج من nonToggleable لأن الميزة بقت مخطَّطة في المهمتين ٩ و١٠). لاحظ
  // إن السجل مش مقياس كافي لـ«الصلاحية شغّالة»: باج المحرك d01fdfdc خلّى
  // treasury_balance_view و dashboard_profit ما يخبّوش حاجة وهما مش في
  // السجل أصلاً.
  // ٢ → ١ (مراجعةُ ما قبل الدمج، 2026-08-17): 'tables_print_bill' خرج —
  // كبسةُ «طباعة الفاتورة» بقت موصولةً بفحصٍ صريحٍ ثم
  // `TableSessionService.requestBill` والطباعة، بدل توست «قيدُ الإنجاز».
  // فاضل 'tables_discount' وحده: زرُّ الخصم لسه ما بُنيش في واجهة الطاولات.
  // ١ → ١٢ (محرّكُ الحجوزات — Task 5، 2026-08-20): أحدَ عشرَ كوداً جديداً
  // دخلوا `PermissionEnforcementRegistry.knownUnenforced` مع نواة محرّك
  // الحجوزات — شاشاتُهم (حجز، قائمة الخدمات، إدارة الموارد، التقارير،
  // الإعدادات) مشروعٌ لاحقٌ لم يُبنَ بعد، وكلُّ كودٍ يخرج من هنا حين تصل
  // شاشتُه للإنتاج (نفسُ نمط كلّ دفعةٍ سابقة هنا). السجلُّ موثَّقٌ فوقُ في
  // `permission_enforcement_registry.dart` بأنه **ينكمش لا يكبر**؛ نموُّه
  // هنا استثناءٌ مقصودٌ لميزةٍ لم تُبنَ إطلاقاً — لا انجرافاً — والتوثيقُ
  // الكاملُ للسبب في تعليق السجل نفسه هناك (بند «الحجوزات»). ولحقَ هذا
  // الاختبارَ أحمرَ عبر كوميتَي Task 5 قبل أن يُكتشف هنا (مهمّة علَم
  // الحجوزات ٧، 2026-08-21) لأن Task 5 شغّل اختباراتِه المستهدفة فقط —
  // نفسُ نمط التأخّر الموثَّق فوق: «أي دفعة بتشيل من السجل لازم تحدّث الرقم
  // ده في نفس الكوميت»، وهنا دفعةٌ بتضيف فينطبق نفسُ الدرس على الإضافة.
  // ١٢ → ١١ (‏المرحلة ٣ من طريق الـGo — v167، 2026-08-27): خرج
  // 'bookings_deposit' — نقطةُ `/api/bookings/apply-deposit` تحرسه بـ
  // `ApiUserCtx.requirePermission`. وهو أوّلُ أكواد الحجوزات ينال إنفاذاً،
  // وسبقَ شاشتَه لأنّ خصمَ العربون حدثٌ **ماليّ** لا زرُّ واجهة: العميلُ
  // يُرسله والخادمُ وحدَه يُرحّله. والعشرةُ الباقيةُ تنتظر شاشاتِها.
  //
  // ⚠️ وهذا الملفُّ و`permission_enforcement_coverage_test.dart` عقدان
  // **متقابلان**: ذاك يحمرّ لكودٍ صار منفَّذاً وبقي في السجلّ، وهذا يحمرّ
  // لتغيّرٍ في السجلّ بلا مراجعة. فنقلُ كودٍ واحدٍ يُحمِّر أحدَهما حتماً ما
  // لم يُعدَّلا **معاً** — وقع فعلاً في هذه الدفعة: أُصلح الأوّلُ فاحمرّ
  // الثاني في دورة بوّابةٍ تالية.
  // ١١ → ٣ (P2، 2026-10-18): شاشةُ الحجوزات وصلت — خرج ثمانيةٌ منفَّذون في
  // `bookings_picpos/` والخريطة (view/add/cancel/status/services_manage/
  // resources_manage/reports/settings). وبقي `bookings_edit` و`bookings_assign`
  // بلا سطحٍ في الواجهة اليوم (لا تعديلَ لحجزٍ قائم ولا إسنادَ لاحقاً).
  test('knownUnenforced فيه خصمَ الطاولة وكودَي حجزٍ بلا سطحٍ بعد', () {
    expect(
      PermissionEnforcementRegistry.knownUnenforced,
      {
        'tables_discount',
        'bookings_edit',
        'bookings_assign',
        // ⚠️ `bookings_deposit` **ليست هنا** منذ v167 (‏المرحلة ٣،
        //    2026-08-27): نقطةُ `/api/bookings/apply-deposit` تحرسها بـ
        //    `ApiUserCtx.requirePermission`، فهي أوّلُ أكواد الحجوزات تنال
        //    إنفاذاً حقيقيّاً — لأنّ خصمَ العربون حدثٌ **ماليٌّ سبق شاشتَه**.
        //
        //    وهذا الملفُّ و`permission_enforcement_coverage_test.dart`
        //    عقدان **متقابلان**: ذاك يفشل لكودٍ صار منفَّذاً وبقي مسجَّلاً،
        //    وهذا يفشل لتغيّرٍ في السجلّ بلا مراجعة. فأيُّ نقلٍ يمسّ
        //    الاثنين معاً أو يبقى أحدُهما أحمرَ.
      },
      reason:
          'السجل المتوقَّع يقتصر على كودِ خصم الطاولة و`bookings_edit` و'
          '`bookings_assign` (بلا سطحٍ في الواجهة بعد). لو ظهر كودٌ تانٍ أو '
          'اختفى واحدٌ من هذول بلا سببٍ موثَّق، يبقى فيه تغيير غير متوقَّع '
          'محتاج مراجعة.',
    );
  });
}
